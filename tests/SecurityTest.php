        $this->assertSame(8, $groups['app']['files']);
        $this->assertSame('v7.4.0', $groups['symfony/http-kernel']['version']);
        // Paths relative to the package root; non-code files are not part of the digest.
        $this->assertSame(2, $groups['symfony/http-kernel']['files']);
        $this->assertSame($this->digest([
            'Kernel.php' => hash('sha256', '<?php class Kernel {}'),
            'Resources/js/profiler.js' => hash('sha256', 'console.log(1);'),
        ]), $groups['symfony/http-kernel']['digest']);
        // A branch is versioned by its commit, or every new commit would look like a modification.
        $this->assertSame('dev-main#0123456789ab', $groups['acme/tools']['version']);
        $this->assertSame($this->digest(['src/Tool.php' => hash('sha256', '<?php class Tool {}')]), $groups['acme/tools']['digest']);

        $files = array_column($payload['files'], 'role', 'path');
        $this->assertSame([
            'public/index.php' => 'entry', 'bin/console' => 'entry', '.env' => 'config', '.env.local' => 'config',
            'config/bundles.php' => 'config', 'public/.htaccess' => 'server',
        ], $files);
        $env = array_values(array_filter($payload['files'], static function (array $file): bool {
            return $file['path'] === '.env.local';
        }))[0];
        $this->assertSame(hash_file('sha256', $this->root.'/.env.local'), $env['sha256']);

        $suspicious = array_column($payload['suspicious'], null, 'path');
        ksort($suspicious);
        $this->assertSame([
            'public/info.php', 'public/uploads/.cache', 'public/uploads/2024/shell.php', 'public/uploads/avatars/me.jpg',
            'public/uploads/media/.htaccess', 'storage/media/evil.phtml',
