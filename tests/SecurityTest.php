        $cache->save($item->set(['at' => time() - 600, 'values' => [
            'code_writable' => true, 'display_errors' => false, 'exec_available' => true,
        ]]));
        $reporter = SecurityFactory::create([
            'token' => 'project', 'private_key' => 'secret', 'url' => 'https://dockray.example', 'enabled' => true,
