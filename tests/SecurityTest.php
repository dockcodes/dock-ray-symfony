        $this->assertSame('hidden_directory', $suspicious['public/uploads/.cache']['kind']);
        $this->assertSame('php_in_uploads', $suspicious['public/uploads/2024/shell.php']['kind']);
        $this->assertSame(['eval', 'request_exec'], $suspicious['public/uploads/2024/shell.php']['indicators']);
        $this->assertSame('php_in_media', $suspicious['public/uploads/avatars/me.jpg']['kind']);
        $this->assertSame(['request_exec', 'shell_exec'], $suspicious['public/uploads/avatars/me.jpg']['indicators']);
        // A handler that runs PHP in uploads is reported; `php_flag engine off` is not.
        $this->assertSame('suspicious_code', $suspicious['public/uploads/media/.htaccess']['kind']);
        $this->assertSame(['php_handler'], $suspicious['public/uploads/media/.htaccess']['indicators']);
        $this->assertSame('php_in_uploads', $suspicious['storage/media/evil.phtml']['kind']);

        $this->assertSame(['code_writable', 'display_errors', 'exec_available', 'debug_mode', 'debug_tools'], array_keys($payload['posture']));
        $this->assertFalse($payload['posture']['display_errors']);
        $this->assertTrue($payload['posture']['debug_mode']);
        $this->assertTrue($payload['posture']['debug_tools']);

        // The server's interval is clamped to 24 h; nothing more is due before that.
        $this->assertSame(['status' => 'not_due'], $reporter->report());
        $state = json_decode((string) file_get_contents($this->root.'/state/state.json'), true);
        $this->assertGreaterThanOrEqual($before + 86400, $state['next_at']);
        $this->assertLessThanOrEqual(time() + 86400, $state['next_at']);
        $this->assertSame(2, $reporter->last()['findings']['critical']);
        $this->assertSame(0700, fileperms($this->root.'/state') & 0777);
        $this->assertSame(0600, fileperms($this->root.'/state/state.json') & 0777);
        $this->assertSame(0600, fileperms($this->root.'/state/hashes.json') & 0777);
        $this->assertStringNotContainsString('not-a-real', (string) file_get_contents($this->root.'/state/hashes.json'));
    }

