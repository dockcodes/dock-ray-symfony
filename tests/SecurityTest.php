        $this->assertSatisfiesIngestRules($payload);
        $this->assertSame(1, $payload['schema']);
        $this->assertSame('php', $payload['platform']);
        $this->assertSame(PHP_VERSION, $payload['platform_version']);
        $this->assertSame(RayBundle::VERSION, $payload['agent_version']);
        $this->assertSame('https://app.example.com', $payload['site_url']);
        $this->assertFalse($payload['scan']['truncated']);
        $this->assertGreaterThan(0, $payload['scan']['files']);

