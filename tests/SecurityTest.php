    public function test_bundle_registers_command_schedule_and_posture_listener(): void
    {
        foreach (['0', '1'] as $enabled) {
            $_ENV['DOCKRAY_TEST_SECURITY'] = $enabled;
            $kernel = new SecurityKernel($this->root);

            try {
                $kernel->boot();
                $application = new Application($kernel);
                $tester = new CommandTester($application->find('ray:security'));
                // Enabled without credentials: nothing is scanned or sent.
                $this->assertSame($enabled === '0' ? 0 : 1, $tester->execute([]));
                $this->assertStringContainsString($enabled === '0' ? 'disabled' : 'not_configured', $tester->getDisplay());

                $debug = new CommandTester($application->find('debug:scheduler'));
                $this->assertSame(0, $debug->execute([]));
                $this->assertStringContainsString('dockray_security', $debug->getDisplay());

                $container = $kernel->getContainer()->get('test.service_container');
                $this->assertTrue($container->has('messenger.transport.scheduler_dockray_security'));
                $this->assertSame($enabled === '1', $container->get(SecurityReporter::class)->enabled());

                // Resolving the dispatcher's listeners would build the hub and its global
                // error handlers; the subscriber service itself is enough here.
                $this->assertInstanceOf(SecurityPostureListener::class, $container->get(SecurityPostureListener::class));
                $this->assertArrayHasKey(KernelEvents::TERMINATE, SecurityPostureListener::getSubscribedEvents());
                $this->assertTrue($container->get('event_dispatcher')->hasListeners(KernelEvents::TERMINATE));
            } finally {
                $kernel->shutdown();
            }
        }

        $this->assertDirectoryDoesNotExist($this->root.'/var/dockray/security');
    }

    public function test_schedule_is_empty_when_disabled_and_ticks_every_five_minutes_when_enabled(): void
    {
        $this->assertCount(0, (new SecuritySchedule(false))->getSchedule()->getRecurringMessages());
        $provider = new SecuritySchedule(true);
        $schedule = $provider->getSchedule();
        $this->assertSame($schedule, $provider->getSchedule());
        $messages = $schedule->getRecurringMessages();
        $this->assertCount(1, $messages);
        $message = array_values($messages)[0];
        $context = new \Symfony\Component\Scheduler\Generator\MessageContext('dockray_security', $message->getId(), $message->getTrigger(), new \DateTimeImmutable);
        $this->assertInstanceOf(ReportSecurity::class, iterator_to_array($message->getMessages($context))[0]);
        $first = $message->getTrigger()->getNextRunDate(new \DateTimeImmutable('2026-01-01 12:00:00'));
        $this->assertSame(300, $message->getTrigger()->getNextRunDate($first)->getTimestamp() - $first->getTimestamp());
    }

