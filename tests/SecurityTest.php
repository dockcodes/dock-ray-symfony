    public function test_posture_listener_measures_page_views_only_and_builds_the_reporter_lazily(): void
    {
        $kernel = $this->createMock(\Symfony\Component\HttpKernel\HttpKernelInterface::class);
        $terminate = static function (Request $request) use ($kernel): TerminateEvent {
            return new TerminateEvent($kernel, $request, new Response);
        };

        $off = new SecurityPostureListener(false, function (): SecurityReporter {
            $this->fail('The reporter must not be built while the report is disabled.');
        });
        $off->onTerminate($terminate(Request::create('/')));

        $cache = new ArrayAdapter;
        $built = 0;
        $listener = new SecurityPostureListener(true, function () use ($cache, &$built): SecurityReporter {
            $built++;

            return new SecurityReporter($this->auth(), true, $this->root, $this->root.'/state', ['console' => false], null, null, $cache);
        });

        $ajax = Request::create('/cart');
        $ajax->headers->set('X-Requested-With', 'XMLHttpRequest');
        $json = Request::create('/products');
        $json->headers->set('Accept', 'application/json');
        foreach ([$ajax, $json, Request::create('/api'), Request::create('/api/orders')] as $request) {
            $listener->onTerminate($terminate($request));
        }
        $this->assertSame(0, $built);
        $this->assertFalse($cache->getItem(SecurityReporter::WEB_POSTURE_KEY)->isHit());

        $listener->onTerminate($terminate(Request::create('/apiary')));
        $this->assertSame(1, $built);
        $stored = $cache->getItem(SecurityReporter::WEB_POSTURE_KEY)->get();
        $this->assertSame(['code_writable', 'display_errors', 'exec_available'], array_keys($stored['values']));
        $this->assertEqualsWithDelta(time(), $stored['at'], 5);

        // A failing reporter never breaks the response that already went out.
        $broken = new SecurityPostureListener(true, static function (): SecurityReporter {
            throw new \RuntimeException('boom');
        });
        $broken->onTerminate($terminate(Request::create('/')));
    }

