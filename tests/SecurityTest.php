    public function test_early_fatal_reporter_sends_one_event_and_prints_nothing(): void
    {
        if (! function_exists('proc_open')) {
            $this->markTestSkipped('proc_open is not available.');
        }

        $capture = $this->root.'/captured.json';
        file_put_contents($this->root.'/router.php', '<?php file_put_contents('.var_export($capture, true).', json_encode(['
            .'"uri" => $_SERVER["REQUEST_URI"], "auth" => getallheaders()["Authorization"] ?? null, '
            .'"agent" => $_SERVER["HTTP_USER_AGENT"] ?? null, "body" => file_get_contents("php://input")])); echo "{}";');
        file_put_contents($this->root.'/broken.php', "<?php\n\$value = 1;\ndockray_undefined_function(\$value);\n");

        $port = $this->freePort();
        $server = proc_open([PHP_BINARY, '-S', '127.0.0.1:'.$port, $this->root.'/router.php'], [1 => ['file', '/dev/null', 'w'], 2 => ['file', '/dev/null', 'w']], $pipes);
        $this->assertIsResource($server);

        try {
            $this->waitForPort($port);
            $prepend = dirname(__DIR__).'/resources/early-fatal.php';
            $token = 'early'.bin2hex(random_bytes(4));

            // Without credentials it does nothing at all.
            [$output] = $this->runPhp(['-d', 'display_errors=0', '-d', 'log_errors=0', '-d', 'auto_prepend_file='.$prepend, $this->root.'/broken.php'], ['RAY_URL' => 'http://127.0.0.1:'.$port]);
            $this->assertSame('', $output);
            $this->assertFileDoesNotExist($capture);

            [$output, $exit] = $this->runPhp(['-d', 'display_errors=0', '-d', 'log_errors=0', '-d', 'auto_prepend_file='.$prepend, $this->root.'/broken.php'], [
                'RAY_TOKEN' => $token, 'RAY_PRIVATE_KEY' => 'early-secret', 'RAY_URL' => 'http://127.0.0.1:'.$port,
                'APP_ENV' => 'prod', 'RAY_RELEASE' => 'v9',
            ]);
            $this->assertSame('', $output);
            $this->assertSame(255, $exit);
            $this->assertFileExists($capture);
            $request = json_decode((string) file_get_contents($capture), true);
            $this->assertSame('/api/v1/'.$token.'/project', $request['uri']);
            $this->assertSame('Bearer early-secret', $request['auth']);
            $this->assertStringStartsWith('dockray-symfony-early/', $request['agent']);

            $event = json_decode($request['body'], true);
            $this->assertSame(['name' => 'dockray.symfony.early', 'version' => RayBundle::VERSION], $event['sdk']);
            $this->assertSame('fatal', $event['level']);
            $this->assertSame('prod', $event['environment']);
            $this->assertSame('v9', $event['release']);
            $this->assertSame('Error', $event['exception']['values'][0]['type']);
            $this->assertSame('Call to undefined function dockray_undefined_function()', $event['exception']['values'][0]['value']);
            $frames = $event['exception']['values'][0]['stacktrace']['frames'];
            $this->assertSame(3, end($frames)['lineno']);
            $this->assertStringNotContainsString('early-secret', $request['body']);
        } finally {
            proc_terminate($server);
            proc_close($server);
        }
    }

    /**
     * The rules of `SecurityReportIngest::validate()`, field by field.
     *
     * @param array<string, mixed> $payload
     */
    private function assertSatisfiesIngestRules(array $payload): void
    {
        $this->assertSame(1, $payload['schema']);
        $this->assertContains($payload['platform'], self::PLATFORMS);
        foreach (['platform_version' => 64, 'php_version' => 64, 'agent_version' => 32, 'site_url' => 2048] as $key => $max) {
            if (isset($payload[$key])) {
                $this->assertIsString($payload[$key]);
                $this->assertLessThanOrEqual($max, mb_strlen($payload[$key]));
            }
        }
        $this->assertIsInt($payload['scan']['files']);
        $this->assertIsInt($payload['scan']['duration_ms']);
        $this->assertIsBool($payload['scan']['truncated']);
        $this->assertArrayNotHasKey('core', $payload);

        $this->assertLessThanOrEqual(1500, count($payload['groups']));
        foreach ($payload['groups'] as $group) {
            $this->assertContains($group['type'], self::GROUP_TYPES);
            $this->assertMatchesRegularExpression('/^[A-Za-z0-9._@\/+-]+$/', $group['slug']);
            $this->assertLessThanOrEqual(191, mb_strlen($group['slug']));
            $this->assertTrue($group['version'] === null || (is_string($group['version']) && mb_strlen($group['version']) <= 64));
            $this->assertIsInt($group['files']);
            $this->assertMatchesRegularExpression('/^[a-fA-F0-9]{64}$/D', $group['digest']);
        }

        $this->assertLessThanOrEqual(500, count($payload['files']));
        foreach ($payload['files'] as $file) {
            $this->assertRelativePath($file['path']);
            $this->assertContains($file['role'], self::FILE_ROLES);
            $this->assertMatchesRegularExpression('/^[a-fA-F0-9]{64}$/D', $file['sha256']);
            $this->assertIsInt($file['size']);
        }

        $this->assertLessThanOrEqual(500, count($payload['suspicious']));
        foreach ($payload['suspicious'] as $entry) {
            $this->assertRelativePath($entry['path']);
            $this->assertContains($entry['kind'], self::SUSPICIOUS_KINDS);
            $this->assertLessThanOrEqual(10, count($entry['indicators'] ?? []));
            foreach ($entry['indicators'] ?? [] as $indicator) {
                $this->assertMatchesRegularExpression('/^[a-z0-9_]+$/D', $indicator);
                $this->assertLessThanOrEqual(32, strlen($indicator));
            }
            foreach (['size', 'mtime'] as $key) {
                if (isset($entry[$key])) {
                    $this->assertIsInt($entry[$key]);
                    $this->assertGreaterThanOrEqual(0, $entry[$key]);
                }
            }
        }

        foreach ($payload['posture'] as $key => $value) {
            $this->assertContains($key, self::POSTURE_KEYS);
            $this->assertIsBool($value);
        }
    }

    /** `SecurityReportIngest::isRelativePath()` plus the 512-character limit. */
    private function assertRelativePath(string $path): void
    {
        $this->assertNotSame('', $path);
        $this->assertLessThanOrEqual(512, mb_strlen($path));
        $this->assertStringStartsNotWith('/', $path);
        $this->assertStringNotContainsString('\\', $path);
        $this->assertDoesNotMatchRegularExpression('/[\x00-\x1F\x7F]/', $path);
        $this->assertNotContains('..', explode('/', $path));
        $this->assertDoesNotMatchRegularExpression('/^[A-Za-z]:/', $path);
    }

    private function withHttp(SecurityReporter $reporter, MockHttpClient $http): SecurityReporter
    {
        $property = new \ReflectionProperty(SecurityReporter::class, 'http');
        $property->setValue($reporter, $http);

        return $reporter;
    }

    private function auth(): AuthData
    {
        return AuthData::create('project', 'secret', 'https://dockray.example');
    }

    /** @param array<string, string> $hashes */
    private function digest(array $hashes): string
    {
        uksort($hashes, 'strcmp');
        $data = '';

        foreach ($hashes as $path => $hash) {
            $data .= $path."\0".$hash."\n";
        }

        return hash('sha256', $data);
    }

    private function freePort(): int
    {
        $socket = stream_socket_server('tcp://127.0.0.1:0');
        $this->assertIsResource($socket);
        $name = stream_socket_get_name($socket, false);
        fclose($socket);

        return (int) substr((string) $name, strrpos((string) $name, ':') + 1);
    }

    private function waitForPort(int $port): void
    {
        for ($attempt = 0; $attempt < 100; $attempt++) {
            $connection = @fsockopen('127.0.0.1', $port, $errno, $error, 0.1);

            if (is_resource($connection)) {
                fclose($connection);

                return;
            }

            usleep(50000);
        }

        $this->fail('The capture server did not start.');
    }

    /**
     * @param list<string>          $arguments
     * @param array<string, string> $environment
     *
     * @return array{0: string, 1: int}
     */
    private function runPhp(array $arguments, array $environment): array
    {
        $process = proc_open(array_merge([PHP_BINARY, '-n'], $arguments), [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, $this->root,
            $environment + ['PATH' => (string) getenv('PATH')]);
        $this->assertIsResource($process);
        $output = stream_get_contents($pipes[1]).stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);

        return [$output, proc_close($process)];
    }
}

