        $this->assertStringNotContainsString($this->root, $sent);
        $this->assertStringNotContainsString(sys_get_temp_dir(), $sent);
        $this->assertStringNotContainsString('not-a-real', $sent);
        $this->assertStringNotContainsString('system(', $sent);
        $this->assertStringNotContainsString('phpinfo', $sent);
        $this->assertStringNotContainsString('secret', $sent);

